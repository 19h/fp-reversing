def allocate(before,pattern,pointer,n):
    pc=MALLOC21 if n==21 else MALLOC48
    assert before['boundary']['pc']==hex(pc) and before['boundary']['registers31'][0]==hex(n)
    v=restore(before);ev=API.event(v,before,pattern,invalid=[(E,4)])
    ev.pop('return32');ev.pop('int_return_upper32_unspecified_fixture');v.set(0,pointer)
    ev.update(return_registers31=[hex(v.reg(j)) for j in range(31)],pointer_return64=hex(pointer),effect_kind='allocation_'+str(n))
    ev['allocated_owner_premise']={'address':hex(pointer),'size_bytes':n,'initial_bytes_defined':False} if pointer else None
    if pointer:
        assert all(not(a<pointer+n and pointer<a+k) for a,k in v.foreign_owners)
        Parent.owner(v,pointer,n)
    API.compact(v);v.cut_stops={COMPARE}
    row=v.interval(pc+4,'original_allocation_return_to_import_unknown_or_emitter_comparison')
    expected=UNKNOWN if n==21 and not pointer else MALLOC48 if n==21 else COMPARE if pointer else FREE21
    assert row['boundary']['pc']==hex(expected),row['boundary']
    return {'pointer_return64':hex(pointer),'API_return_premise':ev,'interval_packed':pack(row)}

def retire(before,pattern):
    assert before['boundary']['pc']==hex(FREE21) and before['boundary']['registers31'][0]==hex(T)
    v=restore(before);ev=API.event(v,before,pattern,invalid=[(T,21),(E,4)])
    ev.pop('return32');ev.pop('int_return_upper32_unspecified_fixture');v.set(0,0xa5b6c7d8e9f01234^pattern)
    ev.update(return_registers31=[hex(v.reg(j)) for j in range(31)],void_return_premise=True,
              retired_owner_premise={'address':hex(T),'size_bytes':21},effect_kind='free_21')
    assert (T,21) in v.foreign_owners;v.foreign_owners.remove((T,21))
    row=API.interval(v,before,ev);assert row['boundary']['pc']==hex(UNKNOWN)
    return {'API_return_premise':ev,'interval_packed':pack(row)}

def case(index,parent):
    before=unpack(parent['allocation_cases'][1]['interval_packed']);pattern=1-parent['ABI_clobber_pattern']
    a21=[allocate(before,pattern,p,21) for p in [0,T]]
    success=unpack(a21[1]['interval_packed']);a48=[allocate(success,pattern,p,48) for p in [0,U]]
    free=retire(unpack(a48[0]['interval_packed']),pattern)
    before=unpack(a48[1]['interval_packed']);v=restore(before);API.compact(v);v.cut_stops={TWIST,ADMISSION}
    comparison=v.interval(COMPARE,'original_comparison_leaf_and_counter_route_to_twist')
    assert comparison['boundary']['pc']==hex(TWIST)
    return {'parent_context_index':index,'parent_SIDB_context_index':parent['parent_context_index'],
            'parent_SIDN_query_index':parent['parent_SIDN_query_index'],'ABI_clobber_pattern':pattern,
            'allocation21_cases':a21,'allocation48_cases':a48,'free21_return':free,
            'refill_comparison':{'interval_packed':pack(comparison)}}

def items(c):
    yield from c['allocation21_cases'];yield from c['allocation48_cases'];yield c['free21_return'];yield c['refill_comparison']

def context_intervals(c):
    for x in items(c):yield unpack(x['interval_packed'])

def intervals(e):
    for c in e['contexts']:yield from context_intervals(c)

def source():
    spans=[('allocator21_return',MALLOC21+4,0x100934318),('allocator48_return',MALLOC48+4,0x1008a106c),
           ('cleanup_field',0x10074aba8,0x10074abfc),('free21_return',FREE21,0x1009326b4),
           ('emitter_caller',0x10093c930,0x10093ca84),('adapter',ADAPTER,0x100add7fc),
           ('emitter_prefix',EMITTER,0x100acdb64),('comparison_request',0x100b32e70,0x100b330bc),
           ('complete_comparison_leaf',COMPARE,0x10041a670)]
    return [{'name':n,'start':hex(a),'end':hex(b),'bytes_hex':IMAGE.read(a,b-a).hex(),
             'instructions':[{'pc':hex(i.address),'mnemonic':i.mnemonic,'operands':i.op_str}
                             for i in CS.disasm(IMAGE.read(a,b-a),a)]} for n,a,b in spans]

def build():
    p=json.loads(read(ROOT/(Parent.P+'_checks.json')));contexts=[];counts=Counter();used=set();number=0
    for j,parent in enumerate(p['contexts']):
        c=case(j,parent);contexts.append(c)
